.include "my-macro"    # подключение файла с макроопределениями

.text

.global _start
_start:
    movl $5, %eax      # число, факториал которого будем считать
    movl $1, %ebx      # сюда записываем результат факториала

L1:
    cmpl  $0, %eax     # проверяем, не закончили ли мы еще считать наш факториал
    je L2              # выходим из цикла, если работа завершена

    imull %eax, %ebx   # умножаем результат на текущее число
    decl  %eax         # уменьшаем текущее число на 1
    jmp   L1           # продолжаем выполнение в цикле, елси работа не завершена

L2:
        Finish         # макрос выхода
.end
