/*
 * Задание 5
 *
 * Вычисление вектора b по формуле:
 *      b(i) = A(k,i) + A(i,1)
 *
 * A — квадратная матрица 6x6
 * Элементы — .long (4 байта)
 *
 * Используется базово-индексная адресация со смещением
 */

.include "my-macro"

.data
# -------- матрица A (6x6) --------
A:
    .long  1,  2,  3,  4,  5,  6
    .long  7,  8,  9, 10, 11, 12
    .long 13, 14, 15, 16, 17, 18
    .long 19, 20, 21, 22, 23, 24
    .long 25, 26, 27, 28, 29, 30
    .long 31, 32, 33, 34, 35, 36

# -------- вектор результата --------
b:
    .long 0,0,0,0,0,0

# -------- параметр --------
k:
    .long 2          # номер строки (0..5)

.text
.global _start

_start:
    subl %esi, %esi      # i = 0

    # edx = k * 24 (длина строки = 6 * 4 байта)
    movl k, %edx
    imull $24, %edx

# -------- цикл по i --------
loop_i:
    cmpl $6, %esi
    je finish

    # ----- A(k,i) -----
    # адрес = A + edx + i*4
    movl A(%edx,%esi,4), %eax

    # ----- A(i,1) -----
    # ecx = i * 24
    movl %esi, %ecx
    imull $24, %ecx
    # адрес = A + ecx + 4 (второй столбец)
    movl A+4(%ecx), %ebx

    # ----- b(i) = A(k,i) + A(i,1) -----
    addl %ebx, %eax
    movl %eax, b(,%esi,4)

    incl %esi
    jmp loop_i

finish:
    # (результат смотрится в отладчике)
    Finish

.end

