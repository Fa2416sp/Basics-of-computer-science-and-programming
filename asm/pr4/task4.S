/*
 * ==============================================================
 *  Лабораторная работа 4 (расширенная версия: 4 + 4.1 + 4.2)
 *
 *  Назначение программы:
 *  ---------------------
 *  Программа считывает ввод пользователя из стандартного ввода
 *  и обрабатывает последовательность однозначных чисел.
 *
 *  Правила ввода:
 *  --------------
 *  1. Числом считается ОДНА цифра '0'..'9', стоящая перед Enter.
 *  2. Перед цифрой может стоять знак '-'.
 *     Примеры корректного ввода:
 *        5<Enter>
 *       -3<Enter>
 *        0<Enter>
 *  3. Все прочие символы игнорируются.
 *
 *  Логика работы:
 *  --------------
 *  - Числа суммируются в 16-битной переменной (тип short).
 *  - При сложении и вычитании контролируется ЗНАКОВОЕ переполнение.
 *  - При переполнении программа завершает работу с сообщением.
 *
 *  После завершения ввода (EOF):
 *  -----------------------------
 *  Итоговая сумма выводится:
 *   - в десятичной системе
 *   - в восьмеричной системе
 *   - в двоичной системе
 *
 *  Цель лабораторной:
 *  ------------------
 *  - работа с вводом/выводом на уровне системных вызовов;
 *  - арифметика и контроль переполнения;
 *  - преобразование чисел в различные системы счисления;
 *  - отладка программ на ассемблере.
 * ==============================================================
 */

.include "my-macro"     # макросы Exit, Getchar, Puts

# --------------------------------------------------------------
# СЕКЦИЯ ДАННЫХ
# --------------------------------------------------------------
.data
sum:        .short 0     # накопленная сумма (16 бит, по заданию)
last_digit: .byte  0     # последняя введённая цифра (0..9)
has_digit:  .byte  0     # флаг: была ли цифра перед Enter
sign:       .byte  0     # знак текущего числа:
                         # 0 — положительное
                         # 1 — отрицательное

# --------------------------------------------------------------
# СЕКЦИЯ BSS (НЕИНИЦИАЛИЗИРОВАННАЯ ПАМЯТЬ)
# --------------------------------------------------------------
.bss
    .lcomm c, 1          # буфер для чтения одного символа
    .lcomm decbuf, 16    # буфер для десятичного представления
    .lcomm octbuf, 16    # буфер для восьмеричного представления
    .lcomm binbuf, 32    # буфер для двоичного представления

# --------------------------------------------------------------
# СЕКЦИЯ КОДА
# --------------------------------------------------------------
.text
.global _start

_start:
    # ----------------------------------------------------------
    # ПРИВЕТСТВИЕ И ПОДСКАЗКА ПОЛЬЗОВАТЕЛЮ
    # ----------------------------------------------------------
    Puts "Введите однозначные числа."
    Puts "Перед цифрой допускается знак '-'."
    Puts "Каждое число вводите с новой строки (Enter)."
    Puts "Для завершения ввода нажмите Ctrl+D."
    Puts ""

    xor %eax, %eax
    xor %ebx, %ebx

# ==============================================================
# ОСНОВНОЙ ЦИКЛ ЧТЕНИЯ ВВОДА
# ==============================================================
read_loop:
    Getchar $c           # чтение одного символа из stdin
    cmpl $0, %eax
    je finish            # EOF — завершение ввода

    # ----------------------------------------------------------
    # Проверка на знак '-'
    # ----------------------------------------------------------
    cmpb $'-', c
    jne check_digit
    movb $1, sign        # запоминаем, что число отрицательное
    jmp read_loop

# --------------------------------------------------------------
# Проверка символа на цифру или Enter
# --------------------------------------------------------------
check_digit:
    cmpb $'\n', c
    je process_digit     # Enter — обрабатываем число

    # если символ не цифра — игнорируем
    cmpb $'9', c
    ja read_loop
    cmpb $'0', c
    jb read_loop

    # ----------------------------------------------------------
    # Символ является цифрой
    # ----------------------------------------------------------
    movb c, %al
    subb $'0', %al       # ASCII → числовое значение 0..9
    movb %al, last_digit
    movb $1, has_digit   # отмечаем, что цифра была
    jmp read_loop

# ==============================================================
# ОБРАБОТКА НАЖАТИЯ ENTER
# ==============================================================
process_digit:
    cmpb $0, has_digit
    je reset_flags       # Enter без цифры — ничего не делаем

    movswl sum, %eax     # текущая сумма → eax
    movzbl last_digit, %ebx  # цифра → ebx

    # ----------------------------------------------------------
    # Выбор операции по знаку числа
    # ----------------------------------------------------------
    cmpb $0, sign
    jne do_sub            # если знак '-', выполняем вычитание

    # ---------- сложение ----------
    addl %ebx, %eax
    jo overflow           # проверка знакового переполнения
    jmp store

do_sub:
    # ---------- вычитание ----------
    subl %ebx, %eax
    jo overflow           # проверка знакового переполнения

store:
    movw %ax, sum         # сохраняем результат в sum

# --------------------------------------------------------------
# Сброс флагов перед следующим вводом
# --------------------------------------------------------------
reset_flags:
    movb $0, has_digit
    movb $0, sign
    jmp read_loop

# ==============================================================
# ОБРАБОТКА ПЕРЕПОЛНЕНИЯ
# ==============================================================
overflow:
    Puts "Ошибка: знаковое переполнение суммы!"
    Exit $1

# ==============================================================
# EOF — ВЫВОД РЕЗУЛЬТАТОВ
# ==============================================================
finish:
    Puts ""
    Puts "Результат вычислений:"

# ---------------- ДЕСЯТИЧНОЕ ----------------
    Puts "Десятичное представление:"

    movswl sum, %eax
    lea decbuf+15, %edi
    movb $0, (%edi)
    movl $10, %ebx

dec_loop:
    decl %edi
    xor %edx, %edx
    idivl %ebx
    addb $'0', %dl
    movb %dl, (%edi)
    test %eax, %eax
    jnz dec_loop

    movl $4, %eax
    movl $1, %ebx
    movl %edi, %ecx
    lea decbuf+16, %edx
    subl %ecx, %edx
    int $0x80

# ---------------- ВОСЬМЕРИЧНОЕ ----------------
    Puts ""
    Puts "Восьмеричное представление:"

    movswl sum, %eax
    lea octbuf+15, %edi
    movb $0, (%edi)
    movl $8, %ebx

oct_loop:
    decl %edi
    xor %edx, %edx
    divl %ebx
    addb $'0', %dl
    movb %dl, (%edi)
    test %eax, %eax
    jnz oct_loop

    movl $4, %eax
    movl $1, %ebx
    movl %edi, %ecx
    lea octbuf+16, %edx
    subl %ecx, %edx
    int $0x80

# ---------------- ДВОИЧНОЕ ----------------
    Puts ""
    Puts "Двоичное представление:"

    movswl sum, %eax
    lea binbuf+31, %edi
    movb $0, (%edi)
    movl $2, %ebx

bin_loop:
    decl %edi
    xor %edx, %edx
    divl %ebx
    addb $'0', %dl
    movb %dl, (%edi)
    test %eax, %eax
    jnz bin_loop

    movl $4, %eax
    movl $1, %ebx
    movl %edi, %ecx
    lea binbuf+32, %edx
    subl %ecx, %edx
    int $0x80

    Puts ""
    Exit $0

