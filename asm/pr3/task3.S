/*
 * ==============================================================
 *  Лабораторная работа 3
 *
 *  Назначение программы:
 *  ---------------------
 *  Программа демонстрирует ввод данных с клавиатуры
 *  и обработку символов на уровне системных вызовов.
 *
 *  Правила работы:
 *  ---------------
 *  - Пользователь вводит символы с клавиатуры.
 *  - Если введён символ цифры ('0'..'9'):
 *      • его код сохраняется в буфер в памяти;
 *      • выводится сообщение об успешном вводе.
 *  - Если введён любой другой символ:
 *      • выводится сообщение об ошибке;
 *      • предлагается повторить ввод.
 *  - Символ перевода строки (Enter) игнорируется.
 *  - При EOF (Ctrl+D) программа завершает работу.
 *
 *  Цель лабораторной:
 *  ------------------
 *  - работа с системным вызовом read;
 *  - проверка кодов символов;
 *  - использование условных переходов;
 *  - запись данных в память;
 *  - отладка программы в kdbg.
 * ==============================================================
 */

.include "my-macro"      # макросы Exit, Getchar, Puts

# --------------------------------------------------------------
# СЕКЦИЯ BSS
# --------------------------------------------------------------
.bss
    .lcomm buf, 100      # буфер для кодов введённых цифр
    .lcomm c, 1          # однобайтовый буфер для чтения символа

# --------------------------------------------------------------
# СЕКЦИЯ КОДА
# --------------------------------------------------------------
.text
.global _start

_start:
    # ----------------------------------------------------------
    # Инициализация
    # ----------------------------------------------------------
    xor %esi, %esi       # esi — индекс текущей позиции в буфере

# ==============================================================
# ВЫВОД ПОДСКАЗКИ ПОЛЬЗОВАТЕЛЮ
# ==============================================================
show_prompt:
    Puts "Введите цифру (0–9) и нажмите Enter."
    Puts "Для завершения ввода нажмите Ctrl+D."
    Puts ""

# ==============================================================
# ОСНОВНОЙ ЦИКЛ ВВОДА
# ==============================================================
kbd_input:
    Getchar $c           # чтение одного символа из stdin

    # ----------------------------------------------------------
    # Проверка на EOF
    # ----------------------------------------------------------
    cmpl $0, %eax
    je finish            # если EOF — завершить программу

    # ----------------------------------------------------------
    # Игнорируем символ перевода строки
    # ----------------------------------------------------------
    cmpb $'\n', c
    je kbd_input

    # ----------------------------------------------------------
    # Проверка: символ больше '9'?
    # ----------------------------------------------------------
    cmpb $'9', c
    ja print_err_msg

    # ----------------------------------------------------------
    # Проверка: символ меньше '0'?
    # ----------------------------------------------------------
    cmpb $'0', c
    jb print_err_msg

    # ----------------------------------------------------------
    # Символ является цифрой
    # ----------------------------------------------------------
    movb c, %al                  # загрузить код символа в al
    movb %al, buf(%esi)          # сохранить код в буфере
    incl %esi                    # перейти к следующей позиции

    Puts "Цифра принята и сохранена."
    jmp show_prompt

# ==============================================================
# ОБРАБОТКА ОШИБОЧНОГО ВВОДА
# ==============================================================
print_err_msg:
    Puts "Ошибка: введён нецифровой символ."
    Puts "Повторите ввод."
    jmp show_prompt

# ==============================================================
# ЗАВЕРШЕНИЕ ПРОГРАММЫ
# ==============================================================
finish:
    Puts ""
    Puts "Ввод завершён. Программа окончена."
    Exit $0

.end

